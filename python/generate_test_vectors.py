"""Generate deterministic vectors for the repository's Animagus profile."""

import argparse
import json
import pathlib
import random
import sys


ROOT = pathlib.Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from python.animagus import (  # noqa: E402
    APPLICATION_AEAD,
    APPLICATION_DAE,
    APPLICATION_TWEAKABLE,
    PAPER_REVISION,
    PROFILE_NAME,
    PROFILE_VERSION,
    TWEAK_BYTES,
    aead_encrypt,
    dae_encrypt,
    encrypt,
    make_tweak,
    tweakable_encrypt,
)


KEY_LENGTHS = (16, 24, 32)
# 167 bytes gives a 135-byte tail: a partial counter block after the first
# eight-block batch.
MESSAGE_LENGTHS = (32, 33, 47, 48, 49, 64, 167, 512, 4096)
TRACED_MESSAGE_LENGTHS = (32, 49)
# (application identifier d, nonce length, associated-data length)
TWEAK_INPUTS = (
    (APPLICATION_AEAD, 1, 0),
    (APPLICATION_AEAD, 12, 0),
    (APPLICATION_AEAD, 12, 13),
    (APPLICATION_AEAD, 12, 32),
    (APPLICATION_AEAD, 16, 0),
    (APPLICATION_AEAD, 16, 47),
    (APPLICATION_AEAD, 12, 200),
    (APPLICATION_TWEAKABLE, 0, 0),
    (APPLICATION_TWEAKABLE, 0, 13),
    (APPLICATION_TWEAKABLE, 0, 47),
    (APPLICATION_TWEAKABLE, 0, 300),
    (APPLICATION_DAE, 0, 0),
)
# The 200- and 300-byte inputs make the MakeTweak frame span a SHA3 rate
# block, with its misaligned 130-bit suffix in the second block.
# (nonce length, associated-data length, application message length)
AEAD_INPUTS = (
    (12, 0, 16), (12, 13, 17), (1, 7, 31), (12, 5, 32), (12, 5, 33),
    (12, 32, 48), (16, 0, 100),
)
DAE_MESSAGE_LENGTHS = (16, 17, 31, 32, 33, 100)
# (context length, message length)
TWEAKABLE_INPUTS = ((0, 32), (13, 33), (47, 64))
PROFILE = PROFILE_NAME
PROVENANCE = (
    f"Normative {PROFILE_NAME} vectors generated by this repository for "
    f"{PAPER_REVISION}"
)
JSON_PATHS = {
    key_len: ROOT / f"test_vectors/ours/Animagus/Animagus_AES{key_len * 8}.json"
    for key_len in KEY_LENGTHS
}
C_PATH = ROOT / "test_vectors/converted/cstruct/animagus_testvecs.c"
H_PATH = ROOT / "test_vectors/converted/cstruct/animagus_testvecs.h"

# JSON group -> (C struct name, scalar fields, buffer fields, C array suffix)
GROUPS = {
    "cases": ("animagus_testvec", (),
              ("key", "tweak", "plaintext", "ciphertext"), "tv"),
    "tweak_cases": ("animagus_tweak_testvec", ("application",),
                    ("key", "nonce", "ad", "tweak"), "tweak_tv"),
    "aead_cases": ("animagus_aead_testvec", (),
                   ("key", "nonce", "ad", "message", "ciphertext"), "aead_tv"),
    "dae_cases": ("animagus_dae_testvec", (),
                  ("key", "message", "ciphertext"), "dae_tv"),
    "tweakable_cases": ("animagus_tweakable_testvec", (),
                        ("key", "context", "plaintext", "ciphertext"),
                        "tweakable_tv"),
}


def _random_bytes(source: random.Random, length: int) -> bytes:
    return bytes(source.randrange(0x100) for _ in range(length))


def _source(*seed: object) -> random.Random:
    return random.Random(repr((PROFILE_NAME,) + seed))


def _vectors(key_len: int) -> dict[str, object]:
    cases = []
    for message_len in MESSAGE_LENGTHS:
        source = _source(key_len, TWEAK_BYTES, message_len, 0)
        key = _random_bytes(source, key_len)
        tweak = _random_bytes(source, TWEAK_BYTES)
        plaintext = _random_bytes(source, message_len)
        if message_len in TRACED_MESSAGE_LENGTHS:
            ciphertext, trace = encrypt(key, tweak, plaintext, trace=True)
        else:
            ciphertext = encrypt(key, tweak, plaintext)
            trace = None
        case = {
            "ciphertext": ciphertext.hex(),
            "key": key.hex(),
            "plaintext": plaintext.hex(),
            "tweak": tweak.hex(),
        }
        if trace is not None:
            case["trace"] = trace
        cases.append(case)

    tweak_cases = []
    for application, nonce_len, ad_len in TWEAK_INPUTS:
        source = _source(key_len, "tweak", application, nonce_len, ad_len)
        key = _random_bytes(source, key_len)
        nonce = _random_bytes(source, nonce_len)
        ad = _random_bytes(source, ad_len)
        tweak_cases.append(
            {
                "ad": ad.hex(),
                "application": application,
                "key": key.hex(),
                "nonce": nonce.hex(),
                "tweak": make_tweak(key, application, nonce, ad).hex(),
            }
        )

    aead_cases = []
    for nonce_len, ad_len, message_len in AEAD_INPUTS:
        source = _source(key_len, "aead", nonce_len, ad_len, message_len)
        key = _random_bytes(source, key_len)
        nonce = _random_bytes(source, nonce_len)
        ad = _random_bytes(source, ad_len)
        message = _random_bytes(source, message_len)
        aead_cases.append(
            {
                "ad": ad.hex(),
                "ciphertext": aead_encrypt(key, nonce, ad, message).hex(),
                "key": key.hex(),
                "message": message.hex(),
                "nonce": nonce.hex(),
            }
        )

    dae_cases = []
    for message_len in DAE_MESSAGE_LENGTHS:
        source = _source(key_len, "dae", message_len)
        key = _random_bytes(source, key_len)
        message = _random_bytes(source, message_len)
        dae_cases.append(
            {
                "ciphertext": dae_encrypt(key, message).hex(),
                "key": key.hex(),
                "message": message.hex(),
            }
        )

    tweakable_cases = []
    for context_len, message_len in TWEAKABLE_INPUTS:
        source = _source(key_len, "tweakable", context_len, message_len)
        key = _random_bytes(source, key_len)
        context = _random_bytes(source, context_len)
        plaintext = _random_bytes(source, message_len)
        tweakable_cases.append(
            {
                "ciphertext": tweakable_encrypt(key, context, plaintext).hex(),
                "context": context.hex(),
                "key": key.hex(),
                "plaintext": plaintext.hex(),
            }
        )

    return {
        "aead_cases": aead_cases,
        "algorithm": f"Animagus-AES{key_len * 8}",
        "cases": cases,
        "dae_cases": dae_cases,
        "normative": True,
        "paper_revision": PAPER_REVISION,
        "profile": PROFILE,
        "profile_version": PROFILE_VERSION,
        "provenance": PROVENANCE,
        "tweak_cases": tweak_cases,
        "tweakable_cases": tweakable_cases,
    }


def _json_bytes(vectors: dict[str, object]) -> bytes:
    return (json.dumps(vectors, indent=2, sort_keys=True) + "\n").encode("ascii")


def _c_bytes(data: bytes, indent: str = "    ") -> list[str]:
    return [
        indent + ", ".join(f"0x{value:02x}" for value in data[offset:offset + 12]) + ","
        for offset in range(0, len(data), 12)
    ]


def _banner(script: str) -> list[str]:
    return [
        "/*",
        f" * Generated by python/{script}.",
        f" * profile: {PROFILE}",
        f" * profile version: {PROFILE_VERSION}",
        f" * paper revision: {PAPER_REVISION}",
        " * normative: yes",
        f" * provenance: {PROVENANCE}",
        " */",
    ]


def _header_bytes() -> bytes:
    lines = _banner("generate_test_vectors.py") + [
        "#pragma once",
        "",
        '#include "testvec.h"',
        "",
    ]
    for struct_name, scalars, buffers, _ in GROUPS.values():
        lines.append(f"struct {struct_name} {{")
        lines.extend(f"    unsigned int {field};" for field in scalars)
        lines.extend(f"    struct testvec_buffer {field};" for field in buffers)
        lines.extend(["};", ""])
    for struct_name, _, _, suffix in GROUPS.values():
        for key_len in KEY_LENGTHS:
            prefix = f"animagus_aes{key_len * 8}_{suffix}"
            lines.append(f"extern const struct {struct_name} {prefix}[];")
            lines.append(f"extern const size_t {prefix}_count;")
        lines.append("")
    return "\n".join(lines).encode("ascii")


def _c_buffer(
    lines: list[str], symbol: str, data: bytes
) -> str:
    if not data:
        return "{ .len = 0U, .data = NULL }"
    lines.append(f"static const uint8_t {symbol}[] = {{")
    lines.extend(_c_bytes(data))
    lines.extend(["};", ""])
    return f"{{ .len = sizeof({symbol}), .data = {symbol} }}"


def _c_source_bytes(all_vectors: dict[int, dict[str, object]]) -> bytes:
    lines = _banner("generate_test_vectors.py") + [
        '#include "animagus_testvecs.h"',
        "",
    ]
    arrays: list[tuple[str, str, list[dict[str, str]]]] = []
    for group, (struct_name, scalars, buffers, suffix) in GROUPS.items():
        for key_len, vectors in all_vectors.items():
            prefix = f"animagus_aes{key_len * 8}_{suffix}"
            entries = []
            for index, case in enumerate(vectors[group]):
                fields = {field: f"{case[field]}U" for field in scalars}
                for field in buffers:
                    symbol = f"{prefix}_{index}_{field}"
                    fields[field] = _c_buffer(lines, symbol,
                                              bytes.fromhex(case[field]))
                entries.append(fields)
            arrays.append((struct_name, prefix, entries))

    for struct_name, prefix, entries in arrays:
        lines.append(f"const struct {struct_name} {prefix}[] = {{")
        for fields in entries:
            lines.append("    {")
            lines.extend(f"        .{name} = {value}," for name, value in fields.items())
            lines.append("    },")
        lines.extend(
            [
                "};",
                f"const size_t {prefix}_count = sizeof({prefix}) / sizeof({prefix}[0]);",
                "",
            ]
        )
    return "\n".join(lines).encode("ascii")


def _generated_files() -> dict[pathlib.Path, bytes]:
    all_vectors = {key_len: _vectors(key_len) for key_len in KEY_LENGTHS}
    files = {
        JSON_PATHS[key_len]: _json_bytes(vectors)
        for key_len, vectors in all_vectors.items()
    }
    files[H_PATH] = _header_bytes()
    files[C_PATH] = _c_source_bytes(all_vectors)
    return files


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = _generated_files()
    if args.check:
        stale = [
            path for path, contents in generated.items()
            if not path.is_file() or path.read_bytes() != contents
        ]
        for path in stale:
            print(f"{path} is out of date", file=sys.stderr)
        if stale:
            return 1
        print(f"All {len(generated)} generated vector files are up to date")
        return 0

    for path, contents in generated.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(contents)
        print(f"Wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
